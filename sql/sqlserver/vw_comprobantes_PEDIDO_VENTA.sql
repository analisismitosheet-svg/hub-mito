-- Pedidos de venta SOLO de la base DRAGONFISH_MITO (servidor vinculado [MITO]).
--
-- Antes juntaba 5 bases y traía por la red el detalle completo de comprobantes
-- (+1,1 millones de renglones) para filtrar acá: tardaba minutos y el puente cortaba.
-- Ahora el filtro y la unión corren en el servidor de MITO (OPENQUERY) y solo viajan
-- los pedidos. Mismas columnas que antes. Respaldo: vw_comprobantes_PEDIDO_VENTA_original.sql
-- (Aplicado el 2026-10-13 a pedido del usuario.)
-- ============================================================
USE VISTAS_CONSOLIDADAS;
GO
ALTER VIEW dbo.[vw_comprobantes_PEDIDO_VENTA] AS
SELECT
  CAST(N'DRAGONFISH_MITO' AS sysname) AS [BD],
  CAST('PEDIDO' AS varchar(60)) COLLATE DATABASE_DEFAULT AS [TIPO_COMPROBANTE],
  CAST(Q.CODIGO AS varchar(38)) COLLATE DATABASE_DEFAULT AS [CODIGO],
  CAST(Q.DESCFW AS varchar(200)) COLLATE DATABASE_DEFAULT AS [DESCFW],
  CAST(Q.FCLIENTE AS varchar(185)) COLLATE DATABASE_DEFAULT AS [FCLIENTE],
  CAST(Q.FVEN AS varchar(10)) COLLATE DATABASE_DEFAULT AS [FVEN],
  CAST(Q.MOTIVO AS varchar(3)) COLLATE DATABASE_DEFAULT AS [MOTIVO],
  CAST(Q.FFCH AS datetime) AS [FFCH],
  CAST(Q.FHORA AS varchar(8)) COLLATE DATABASE_DEFAULT AS [FHORA],
  CAST(Q.FIMPUESTO AS decimal(15,2)) AS [FIMPUESTO],
  CAST(Q.FLETRA AS varchar(1)) COLLATE DATABASE_DEFAULT AS [FLETRA],
  CAST(Q.FNUMCOMP AS decimal(8,0)) AS [FNUMCOMP],
  CAST(Q.FOBS AS varchar(250)) COLLATE DATABASE_DEFAULT AS [FOBS],
  CAST(Q.FPERSON AS varchar(10)) COLLATE DATABASE_DEFAULT AS [FPERSON],
  CAST(Q.FSUBTON AS decimal(15,4)) AS [FSUBTON],
  CAST(Q.FSUBTOT AS decimal(15,4)) AS [FSUBTOT],
  CAST(Q.FTOTAL AS decimal(15,2)) AS [FTOTAL],
  CAST(Q.FTURNO AS decimal(1,0)) AS [FTURNO],
  CAST(Q.FVUELTO AS decimal(15,2)) AS [FVUELTO],
  CAST(Q.GRAVAMEN AS decimal(15,2)) AS [GRAVAMEN],
  CAST(Q.HALTAFW AS varchar(8)) COLLATE DATABASE_DEFAULT AS [HALTAFW],
  CAST(Q.IDCAJA AS decimal(2,0)) AS [IDCAJA],
  CAST(Q.IVASIS AS decimal(10,2)) AS [IVASIS],
  CAST(Q.REMITO AS varchar(15)) COLLATE DATABASE_DEFAULT AS [REMITO],
  CAST(Q.SIGNOMOV AS decimal(2,0)) AS [SIGNOMOV],
  CAST(Q.UALTAFW AS varchar(100)) COLLATE DATABASE_DEFAULT AS [UALTAFW],
  CAST(Q.AFECANT AS decimal(15,2)) AS [AFECANT],
  CAST(Q.CCOLOR AS varchar(6)) COLLATE DATABASE_DEFAULT AS [CCOLOR],
  CAST(Q.EQUIV AS varchar(20)) COLLATE DATABASE_DEFAULT AS [EQUIV],
  CAST(Q.FART AS varchar(15)) COLLATE DATABASE_DEFAULT AS [FART],
  CAST(Q.FBRUTO AS decimal(15,4)) AS [FBRUTO],
  CAST(Q.FCANT AS decimal(8,2)) AS [FCANT],
  CAST(Q.FCFI AS decimal(7,2)) AS [FCFI],
  CAST(Q.FCFITOT AS decimal(15,4)) AS [FCFITOT],
  CAST(Q.FCOLTXT AS varchar(50)) COLLATE DATABASE_DEFAULT AS [FCOLTXT],
  CAST(Q.FMTOIVA AS decimal(15,4)) AS [FMTOIVA],
  CAST(Q.FNETO AS decimal(15,4)) AS [FNETO],
  CAST(Q.FPORIVA AS decimal(5,2)) AS [FPORIVA],
  CAST(Q.FPRECIO AS decimal(12,2)) AS [FPRECIO],
  CAST(Q.FPRUN AS decimal(15,2)) AS [FPRUN],
  CAST(Q.FTATXT AS varchar(50)) COLLATE DATABASE_DEFAULT AS [FTATXT],
  CAST(Q.FTXT AS varchar(100)) COLLATE DATABASE_DEFAULT AS [FTXT],
  CAST(Q.MNDESCI AS decimal(15,4)) AS [MNDESCI],
  CAST(Q.MNTPIVA AS decimal(17,4)) AS [MNTPIVA],
  CAST(Q.MNTPTOT AS decimal(17,4)) AS [MNTPTOT],
  CAST(Q.PRUNCONIMP AS decimal(15,4)) AS [PRUNCONIMP],
  CAST(Q.TALLE AS varchar(5)) COLLATE DATABASE_DEFAULT AS [TALLE]
FROM OPENQUERY([MITO], '
  SELECT C.CODIGO, C.DESCFW, C.FCLIENTE, C.FVEN, C.MOTIVO, C.FFCH, C.FHORA, C.FIMPUESTO, C.FLETRA,
         C.FNUMCOMP, C.FOBS, C.FPERSON, C.FSUBTON, C.FSUBTOT, C.FTOTAL, C.FTURNO, C.FVUELTO,
         C.GRAVAMEN, C.HALTAFW, C.IDCAJA, C.IVASIS, C.REMITO, C.SIGNOMOV, C.UALTAFW,
         D.AFECANT, D.CCOLOR, D.EQUIV, D.FART, D.FBRUTO, D.FCANT, D.FCFI, D.FCFITOT, D.FCOLTXT,
         D.FMTOIVA, D.FNETO, D.FPORIVA, D.FPRECIO, D.FPRUN, D.FTATXT, D.FTXT, D.MNDESCI,
         D.MNTPIVA, D.MNTPTOT, D.PRUNCONIMP, D.TALLE
  FROM DRAGONFISH_MITO.ZooLogic.COMPROBANTEV AS C
  INNER JOIN DRAGONFISH_MITO.ZooLogic.COMPROBANTEVDET AS D ON D.CODIGO = C.CODIGO
  WHERE LTRIM(C.DESCFW) LIKE ''PEDIDO %'' OR LTRIM(RTRIM(C.DESCFW)) = ''PEDIDO''
') AS Q;
GO
